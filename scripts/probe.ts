import { SOMNIA_HIDEKI_TESTNET_ADDRESSES, SomniaMarkets } from "@somnia-chain/markets-sdk";
import { hidekiTestnet } from "@somnia-chain/markets-sdk/chains";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";
const pk = generatePrivateKey();
const m = new SomniaMarkets({ chain: hidekiTestnet, indexerUrl: "https://hideki-dev.smk.somnia.host/v1/graphql", addresses: SOMNIA_HIDEKI_TESTNET_ADDRESSES, privateKey: pk });
const t0 = Date.now();
const perps = await m.client.listPerpMarkets();
console.log("markets", perps.length, Date.now() - t0, "ms");
console.log(JSON.stringify(perps[0], (k, v) => typeof v === "bigint" ? v.toString() : v, 1).slice(0, 2500));
const btc = perps.find((x: any) => x.baseSymbol === "BTC")!;
const acct = privateKeyToAccount(pk).address;
const el = await m.client.getPerpVoucherEligibility(btc.marginBank, acct);
console.log("elig", el);
const camp = await m.client.getPerpVoucherCampaign?.(btc.marginBank).catch((e: any) => e.message);
console.log("campaign", JSON.stringify(camp, (k, v) => typeof v === "bigint" ? v.toString() : v).slice(0, 1500));
const snap = await m.client.getPerpHealthSnapshot(btc.poolAddress);
console.log("snap", JSON.stringify(snap, (k, v) => typeof v === "bigint" ? v.toString() : v).slice(0, 800));
console.log("maxlev", await m.client.getPerpMaxLeverage?.(btc.poolAddress).catch((e: any) => e.message));
process.exit(0);
